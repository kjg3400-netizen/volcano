def shape_of(title):
    t = title or ""
    # ★맨 먼저 본다. 순서가 결과를 바꾼다 —
    #   `중국이 텃밭 싹쓸이`가 '제도'나 '증시·기업'으로 새면 안 된다.
    if is_china_clash(t):
        return "중국·맞대결"
    for name, words in SHAPES:
        if any(w in t for w in words):
            return name
    return FALLBACK
