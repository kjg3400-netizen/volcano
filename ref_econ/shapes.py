def _has(t, words):
    return any(w in t for w in words)


def china_grade(title):
    """중국 소재를 두 등급으로 가른다. 사장님이 시트를 보고 직접 고르시므로
    확실한 것만 남기지 않고 후보를 넓게 주되 등급을 표시한다.

      "맞대결" — 중국 + 자리가 뒤집히는 낱말. 실측으로 확인된 최고 꼴이다
      "관련"   — 중국이 나오지만 대결 구도는 아님. 제목을 보고 판단하실 몫
      ""       — 중국과 무관하거나 군사·외교 기사
    """
    t = title or ""
    if not _has(t, CHINA_WORDS):
        return ""
    if _has(t, MILITARY_WORDS):
        return ""
    return "맞대결" if _has(t, CLASH_WORDS) else "관련"


def is_china_clash(title):
    """중국과 맞붙어 순위가 뒤집히는 구도냐."""
    return china_grade(title) == "맞대결"


