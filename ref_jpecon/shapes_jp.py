# -*- coding: utf-8 -*-
"""
일본판 꼴 분류 + ★대전제 안전 판정.

한국판(`ref_econ/shapes.py`)을 그대로 가져오면 안 된다. 숏단지 최고 꼴은
`한국이 중국에 밀린` 이야기인데, 일본판에서 `日本が負けた` 를 하면
CLAUDE.md 대전제(비난 금지 · 시청자가 일본인)를 정면으로 어긴다.

쇼피드 채널 실측(2026-08-21, 4편이라 잠정):
  7,663회 0.99%  中国客が半減して5210億円消えたのに…逆に売上爆増
  5,643회 1.97%  中国人観光客が激減したのに過去最多の344万人      ← 좋아요율 최고
  4,408회 0.45%  1日券買ったのに出たら再入場できないってガチ？
상위 두 편이 **둘 다** `외국이 줄었는데 일본은 늘었다` 다. 역설이면서
해외 대비인데 **일본이 이긴 쪽**이라 대전제와도 맞는다.
"""
import re

# ── 대전제 위험 낱말 ──────────────────────────────────────────────────
# 주어가 일본(정부·행정)이고 서술어가 실책·후퇴로 흐르는 소재.
# 사실을 지우라는 게 아니라, 이런 소재는 **화살표를 돌리기 어려워** 고르지 않는다.
GOV = ["政府", "経産省", "財務省", "厚労省", "国交省", "総務省", "文科省",
       "省庁", "官僚", "行政", "首相", "大臣", "内閣", "自民", "野党", "国会",
       "日銀", "自治体", "県が", "市が"]
FAIL = ["廃止", "赤字", "失敗", "見送り", "撤退", "断念", "遅れ", "批判",
        "反発", "責任", "問題視", "指摘", "ずさん", "無駄", "不祥事", "隠蔽",
        "改ざん", "破綻", "危機", "崩壊", "衰退", "転落", "低迷", "苦境"]
BURDEN = ["増税", "負担増", "値上げ", "引き上げ", "保険料", "年金削減", "縮小"]
# 일본이 진 대비 — 사실이어도 이 채널에서는 안 쓴다
JP_LOSE = ["日本が負け", "日本は負け", "日本が遅れ", "日本だけ", "日本の敗",
           "抜かれた", "追い抜かれ", "取り残され", "日本離れ"]
# 실명 개인의 불행. 대전제 문제는 아니지만 이 채널에서 만들 소재가 아니다.
MISFORTUNE = ["破産", "自己破産", "逮捕", "書類送検", "訴訟", "解雇", "引退",
              "夜逃げ", "差し押さえ", "借金"]

# ── 잘 되는 꼴 ────────────────────────────────────────────────────────
PARADOX = ["のに", "にもかかわらず", "はずが", "ところが", "逆に", "実は",
           "意外", "まさかの", "'なのに'", "なのに"]
JP_WIN = ["過去最多", "過去最高", "最多", "最高益", "記録", "爆増", "急増",
          "V字", "復活", "好調", "人気殺到", "行列", "完売", "世界一",
          "世界初", "初めて"]
FOREIGN = ["中国", "韓国", "米国", "アメリカ", "台湾", "欧州", "インド",
           "ベトナム", "海外", "外国人", "インバウンド", "訪日"]
COMPANY = ["社", "企業", "ブランド", "チェーン", "店", "メーカー", "創業",
           "社長", "会長", "明暗", "対決", "勝負"]
CURIOUS = ["理由", "ワケ", "わけ", "カラクリ", "仕組み", "なぜ", "本当の",
           "知られざる", "裏側", "からくり"]


def safety(title):
    """대전제 안전도 -1.0 ~ +1.0 과 사유.
    음수면 '일본을 나무라는 쪽으로 흐르기 쉬운 소재'라는 뜻이다."""
    t = title or ""
    sc, why = 0.0, []

    gov = any(w in t for w in GOV)
    fail = any(w in t for w in FAIL)
    if gov and fail:
        sc -= 0.85; why.append("정부+실책")      # 가장 위험한 조합
    elif fail:
        sc -= 0.35; why.append("실책어")
    # ★정부가 주어라는 것만으로 깎지 마라. 대전제가 막는 건 **비난**이지
    #   정부 이야기가 아니다. `霞が関が国産AIを導入`(코멘트 1,017)은 오히려
    #   일본에 좋은 소식인데 '国会答弁' 의 国会 하나로 -0.20 을 먹고 밀렸다.
    if any(w in t for w in BURDEN):
        sc -= 0.40; why.append("국민부담")
    if any(w in t for w in JP_LOSE):
        sc -= 0.70; why.append("일본이짐")
    # 실명 개인의 불행 — 대전제와는 별개지만 이 채널에서 쓸 소재가 아니다.
    # `芸能プロが破産＝俳優・○○氏が代表`(코멘트 540)이 2위로 올라왔었다.
    if any(w in t for w in MISFORTUNE) and re.search(r"[氏|さん|容疑者]", t):
        sc -= 0.55; why.append("실명개인불행")

    # 해외가 줄었는데 일본은 늘었다 — 대전제와 맞으면서 실적도 난 꼴
    if any(w in t for w in FOREIGN) and any(w in t for w in JP_WIN):
        sc += 0.55; why.append("일본이이김")
    if any(w in t for w in PARADOX):
        sc += 0.25; why.append("역설")
    if any(w in t for w in CURIOUS):
        sc += 0.15; why.append("의문형")

    return max(-1.0, min(1.0, sc)), why


SHAPES = [
    # 정부·정책이 먼저다. 여기 걸리면 다른 꼴로 새면 안 된다.
    ("政策・行政", GOV + BURDEN),
    # 채널 상위 두 편의 꼴. 해외 대비인데 일본이 이긴 쪽.
    ("逆説・日本好調", JP_WIN + ["のに", "にもかかわらず", "逆に"]),
    ("企業の明暗", COMPANY + ["最高益", "減益", "増収", "業績", "売上"]),
    ("暮らし・素朴な疑問", ["1日券", "再入場", "チケット", "料金", "スーパー",
                            "コンビニ", "外食", "値段", "定価", "表示", "産地",
                            "サービス", "ルール", "マナー"]),
    ("海外・比較", FOREIGN),
]
FALLBACK = "経済一般"


def shape_of(title):
    t = title or ""
    for name, words in SHAPES:
        if any(w in t for w in words):
            return name
    return FALLBACK
