def safety(title):
    """대전제 안전도 −1.0 ~ +1.0 과 사유."""
    t = (title or "").lower()
    sc, why = 0.0, []

    gov = any(w in t for w in GOV)
    fail = any(w in t for w in FAIL)
    if gov and fail:
        sc -= 0.85
        why.append("정부+실책")
    elif fail:
        sc -= 0.30
        why.append("실책어")
    if any(w in t for w in BURDEN):
        sc -= 0.40
        why.append("국민부담")
    if any(w in t for w in JP_LOSE):
        sc -= 0.70
        why.append("일본이짐")

    if any(w in t for w in MANNER):
        sc += 0.45
        why.append("생활논쟁")
    if any(w in t for w in GENERATION):
        sc += 0.20
        why.append("세대")
    if any(w in t for w in PARADOX):
        sc += 0.25
        why.append("역설")
    if any(w in t for w in CURIOUS):
        sc += 0.20
        why.append("의문형")
    if any(w in t for w in JP_WIN):
        sc += 0.25
        why.append("일본이이김")
    return max(-1.0, min(1.0, sc)), why


