def hard(title):
    """만들면 안 되는 것이면 (사유, 걸린 낱말), 아니면 (None, '')."""
    t = title or ""
    for name, words in HARD_SETS:
        for w in words:
            if w.lower() in t.lower():
                return name, w
    return None, ""


