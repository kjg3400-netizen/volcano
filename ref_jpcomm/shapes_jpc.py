SHORT_MIN = 8
# 짧은 의문형은 앙케트다 (긴 의문형은 기사 제목일 수 있어 안 건드린다)
ASK_SHORT = 22


def title_fit(title):
    """−1 ~ +1. 알맹이 점수. 점수를 ±40% 만 흔드는 보조다."""
    t = (title or "").lower()
    s, hit = 0.0, []
    for w in GOOD:
        if w in t:
            s += 0.30
            hit.append(w)
            if s >= 0.9:
                break
    if NUM.search(title or ""):
        s += 0.25
        hit.append("숫자")
    for w in BAD:
        if w in t:
            s -= 0.50
            hit.append("−" + w)
            break
    # 「」로 인용을 딴 제목은 대개 알맹이가 있다 (누가 뭐라고 했다)
    if re.search(r"[「『][^」』]{4,}[」』]", title or ""):
        s += 0.20
        hit.append("인용")
    n = len(re.sub(r"\s+", "", title or ""))
    if n < SHORT_MIN:
        s -= 0.30
        hit.append("−짧음")
    # 짧은 의문형 = 앙케트 잡담. 긴 의문형은 기사 제목일 수 있어 건드리지 않는다.
    if n < ASK_SHORT and re.search(r"[？?]\s*$", title or ""):
        s -= 0.40
        hit.append("−앙케트")
    # ★물음표 없는 앙케트가 더 많다 — ガルちゃん 은 체언으로 끊는다.
    #   `海外旅行に行ったことない人` · `美容整形で疑問に思っていること`
    #   · `一人暮らしで気をつけている事` 가 6·7·10위로 올라왔다(실측 2026-08-21).
    #   짧고 · 숫자도 인용도 없고 · 체언으로 끝나면 사실이 하나도 없는 잡담이다.
    if (n < ASK_SHORT and re.search(r"(人|こと|事|もの|話|方|系|くん|ちゃん)\s*$", title or "")
            and not NUM.search(title or "")
            and not re.search(r"[「『]", title or "")):
        s -= 0.45
        hit.append("−나열형")
    return max(-1.0, min(1.0, s)), hit


